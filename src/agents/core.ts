/** Maps an agent's tool name to one of the kinds in `SessionSummary.tools`. */
export function toolKind(name: string): string {
  const lower = name.toLowerCase();
  if (lower.startsWith("mcp__") || lower.startsWith("mcp_")) return "mcp";
  return KINDS[lower] ?? lower;
}

export function count(record: Record<string, number>, key: string, by = 1): void {
  record[key] = (record[key] ?? 0) + by;
}

// Text that agents (or the apps wrapping them, like T3 Code) send as a user
// message but that the person did not type.
const INJECTED = [
  /^<(system-reminder|task-notification|local-command-[a-z]+|environment_context|user_instructions|INSTRUCTIONS|turn_aborted|skill|recommended_plugins|permissions instructions|app-context|collaboration_mode)\b/,
  /^# AGENTS\.md instructions/,
  /^Caveat: The messages below were generated by the user while running local commands/,
  /^This session is being continued from a previous conversation/,
  /^\[Request interrupted by user/,
  /^Context handoff \(/,
  /^Delegated tasks? node:/,
  /^<monitor-event\b/,
  /^Background command completed \(exit/,
  /^Continue the task from where you left off\./,
  /^Act as the [\w -]+ sub-agent for this task/,
];

// Blocks that apps wrapping an agent (T3 Code, Synara) add around the typed text.
// When T3 Code adds instructions, the typed text itself is in <user_request>.
const WRAPPERS = /<(system-reminder|runtime_info|pull_request_linking|t3_code_instructions|synara_host_context)>[\s\S]*?<\/\1>/g;

/** The person's own words, or "" when the message is injected context. */
export function cleanPrompt(raw: string): string {
  const request = /<user_request>([\s\S]*?)<\/user_request>/.exec(raw)?.[1];
  const text = (request ?? raw.replace(WRAPPERS, "")).trim();
  if (!text || INJECTED.some((pattern) => pattern.test(text))) return "";
  return text;
}

/** Added and removed lines of a unified diff, ignoring the ---/+++ file headers. */
export function diffLines(diff: string): { added: number; removed: number } {
  let added = 0;
  let removed = 0;
  for (const line of diff.split("\n")) {
    if (line.startsWith("+") && !line.startsWith("+++")) added++;
    else if (line.startsWith("-") && !line.startsWith("---")) removed++;
  }
  return { added, removed };
}

export function lineCount(text: string): number {
  if (!text) return 0;
  return text.endsWith("\n") ? text.split("\n").length - 1 : text.split("\n").length;
}

/**
 * Streams a JSONL file and yields each parsed record. `keep` sees the raw line
 * first so readers can skip large records they never use without parsing them.
 * Malformed lines are skipped: sessions are often still being written. A
 * missing file yields nothing: agents leave half-created session folders.
 */
export async function* jsonl<T>(path: string, keep?: (line: string) => boolean): AsyncGenerator<T> {
  const file = Bun.file(path);
  if (!(await file.exists())) return;
  const decoder = new TextDecoder();
  let buffer = "";
  const parse = (line: string): T | undefined => {
    if (!line || (keep && !keep(line))) return undefined;
    try {
      return JSON.parse(line) as T;
    } catch {
      return undefined;
    }
  };
  for await (const chunk of file.stream()) {
    buffer += decoder.decode(chunk, { stream: true });
    let start = 0;
    let end = buffer.indexOf("\n");
    while (end !== -1) {
      const record = parse(buffer.slice(start, end));
      if (record !== undefined) yield record;
      start = end + 1;
      end = buffer.indexOf("\n", start);
    }
    buffer = buffer.slice(start);
  }
  const last = parse(buffer + decoder.decode());
  if (last !== undefined) yield last;
}

/** Runs `fn` over `items` with at most `limit` in flight, keeping input order. */
export async function mapLimit<T, R>(items: T[], limit: number, fn: (item: T) => Promise<R>): Promise<R[]> {
  const results: R[] = new Array(items.length);
  let next = 0;
  const worker = async () => {
    while (next < items.length) {
      const index = next++;
      results[index] = await fn(items[index]!);
    }
  };
  await Promise.all(Array.from({ length: Math.min(limit, items.length) }, worker));
  return results;
}

/** Absolute paths matching `pattern` under `dir`, or [] when `dir` does not exist. */
export async function findFiles(dir: string, pattern: string): Promise<string[]> {
  const found: string[] = [];
  try {
    for await (const path of new Bun.Glob(pattern).scan({ cwd: dir, absolute: true })) found.push(path);
  } catch {
    // Not installed.
  }
  return found;
}
