import type { AgentId, SessionSummary } from "../types.ts";

export const IDLE_GAP_MS = 10 * 60 * 1000;

export function emptySummary(agent: AgentId, id: string): SessionSummary {
  return {
    agent,
    id,
    title: "",
    cwd: "",
    start: 0,
    end: 0,
    activeMs: 0,
    prompts: [],
    models: {},
    tools: {},
    commands: [],
    tokens: { input: 0, output: 0 },
    linesAdded: 0,
    linesRemoved: 0,
  };
}

/** First, last and active time of a list of record timestamps (0 and NaN are ignored). */
export function span(times: number[]): { start: number; end: number; activeMs: number } {
  const sorted = times.filter((t) => t > 0).sort((a, b) => a - b);
  let activeMs = 0;
  for (let i = 1; i < sorted.length; i++) {
    const gap = sorted[i]! - sorted[i - 1]!;
    if (gap <= IDLE_GAP_MS) activeMs += gap;
  }
  return { start: sorted[0] ?? 0, end: sorted[sorted.length - 1] ?? 0, activeMs };
}

